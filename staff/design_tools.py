"""Free design fixes for Avery (Oct 27, 2026 audit).

No new service, no API key, no subscription:
- Text-free generation guardrails: the image model must NEVER render text.
  All text is added afterwards with a real font (Pillow), so it cannot garble.
- Real-font overlay: Pillow + a real TTF font. Brand fonts (Cormorant Garamond
  headings, Jost body) are used automatically if dropped into work/fonts/ as
  CormorantGaramond-Regular.ttf / Jost-Regular.ttf; otherwise DejaVu is used.
  Never use the image model to spell a brand name or a personalization.
- 300-DPI wrap builder: common 20oz straight skinny starting template
  9.3 x 8.2 inches = 2790 x 2460 px at 300 DPI. This is a MARKET starting
  point, NOT James's verified blank size — measure the actual blank before
  printing. The builder stamps that warning into its return value.
- Pre-publish checklist: a design must pass every check before it is
  published or sent to a customer. Visual product confirmation (tumbler, not
  can/mug/card) is a manual confirm — code cannot reliably vision-check it
  without a vision model call, so the checklist never auto-passes it.
"""
from pathlib import Path

TEXT_FREE_SUFFIX = (
    ", no text, no letters, no words, no numbers, no brand name, "
    "no logo text, blank oval nameplate for personalization, "
    "single 20oz straight skinny tumbler only, not a can, not a mug, "
    "not a greeting card, not a shirt"
)

WRAP_WIDTH_IN = 9.3
WRAP_HEIGHT_IN = 8.2
WRAP_DPI = 300
WRAP_WIDTH_PX = int(WRAP_WIDTH_IN * WRAP_DPI)  # 2790
WRAP_HEIGHT_PX = int(WRAP_HEIGHT_IN * WRAP_DPI)  # 2460
WRAP_WARNING = (
    "Template is a common 20oz straight skinny starting size (9.3 x 8.2 in), "
    "NOT a verified blank size. Measure the actual blank before printing."
)


PRODUCT_LOCKS = {
    "tumbler": "blank oval nameplate for personalization, single 20oz straight skinny tumbler only, not a can, not a mug, not a greeting card, not a shirt",
    "snow globe tumbler": "single snow globe tumbler only, with a clear snow globe section, not a regular tumbler, not a can, not a mug",
    "acrylic tumbler": "single clear acrylic snow globe tumbler only, not a regular tumbler, not a can, not a mug",
    "keychain": "single round keychain with metal ring only, not a tumbler, not a pen, not a card",
    "pen": "single customizable pen only, not a tumbler, not a keychain, not a pencil",
    "luggage tag": "single luggage tag only, not a tumbler, not a keychain, not a card",
    "shirt": "single t-shirt on a clean background only, not a tumbler, not a hoodie, not a model wearing it",
    "puzzle": "single jigsaw puzzle box with puzzle pieces only, not a tumbler, not a board game, not a card",
    "bookmark": "single bookmark only, flat, not a tumbler, not a card, not a book",
    "ornament": "single Christmas ornament only, round, with a hanging loop, not a tumbler, not a bauble cluster, not a card",
}

def build_text_free_prompt(prompt, product="tumbler"):
    """Append text-free + product-lock guardrails to a design prompt.

    `product` selects the product lock; default is tumbler for backwards
    compatibility with existing callers and tests.
    """
    prompt = (prompt or "").strip()
    if not prompt:
        raise ValueError("Design prompt is empty.")
    lowered = prompt.lower()
    if "no text" in lowered:
        return prompt
    lock = PRODUCT_LOCKS.get(str(product).lower(), f"single {product} only")
    suffix = (
        ", no text, no letters, no words, no numbers, no brand name, "
        "no logo text, blank personalization area if applicable, " + lock
    )
    return prompt.rstrip(",. ") + suffix


def _load_font(root, font_name, size):
    from PIL import ImageFont
    candidates = []
    if root is not None:
        fonts_dir = Path(root) / "work" / "fonts"
        if font_name == "cormorant":
            candidates.append(fonts_dir / "CormorantGaramond-Regular.ttf")
        elif font_name == "jost":
            candidates.append(fonts_dir / "Jost-Regular.ttf")
        candidates.append(fonts_dir / f"{font_name}.ttf")
    candidates.extend([
        Path("/usr/share/fonts/truetype/dejavu/DejaVuSerif.ttf"),
        Path("/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf"),
    ])
    for path in candidates:
        try:
            if path.exists():
                return ImageFont.truetype(str(path), size)
        except Exception:
            continue
    return ImageFont.load_default()


def overlay_text(image_path, output_path, text, font_name="jost", size=120, color="#C6A15B", position="bottom-center"):
    """Overlay REAL text (real font, Pillow) on an image. Returns output path.

    This is the fix for AI text garbling: text is never generated by the
    image model. `text` must be short (a name, a brand, a short phrase).
    `position`: bottom-center, center, or top-center.
    """
    from PIL import Image, ImageDraw
    if not text or not str(text).strip():
        raise ValueError("Overlay text is empty.")
    if len(str(text)) > 60:
        raise ValueError("Overlay text is too long (max 60 characters) — keep personalizations short.")
    src = Path(image_path)
    if not src.exists():
        raise FileNotFoundError(f"Design image not found: {src}")
    with Image.open(src) as im:
        im = im.convert("RGB")
        font = _load_font(None, font_name, size)
        draw = ImageDraw.Draw(im)
        bbox = draw.textbbox((0, 0), str(text), font=font)
        tw, th = bbox[2] - bbox[0], bbox[3] - bbox[1]
        if position == "center":
            x, y = (im.width - tw) // 2, (im.height - th) // 2
        elif position == "top-center":
            x, y = (im.width - tw) // 2, 40
        else:  # bottom-center
            x, y = (im.width - tw) // 2, im.height - th - 60
        # Dark backing strip so gold/white text stays readable on any art.
        draw.rectangle([x - 20, y - 10, x + tw + 20, y + th + 10], fill=(18, 16, 12))
        draw.text((x, y), str(text), font=font, fill=color)
        out = Path(output_path)
        out.parent.mkdir(parents=True, exist_ok=True)
        im.save(out, format="PNG", dpi=(WRAP_DPI, WRAP_DPI))
    return str(out)


def build_wrap(image_path, output_path, width_in=WRAP_WIDTH_IN, height_in=WRAP_HEIGHT_IN, dpi=WRAP_DPI):
    """Build a 300-DPI print wrap canvas from a design image.

    Fits the source to the wrap aspect (center-crop, Lanczos) so the wrap
    has no blank bars and no distortion. Returns a dict with dimensions
    and the template warning — the warning is part of the result, not a comment.
    """
    from PIL import Image
    src = Path(image_path)
    if not src.exists():
        raise FileNotFoundError(f"Design image not found: {src}")
    w_px, h_px = int(width_in * dpi), int(height_in * dpi)
    if w_px <= 0 or h_px <= 0:
        raise ValueError("Wrap size must be positive.")
    with Image.open(src) as im:
        im = im.convert("RGB")
        # Center-crop to wrap aspect, then resize with Lanczos.
        target_aspect = w_px / h_px
        src_aspect = im.width / im.height
        if src_aspect > target_aspect:
            new_w = int(im.height * target_aspect)
            left = (im.width - new_w) // 2
            im = im.crop((left, 0, left + new_w, im.height))
        else:
            new_h = int(im.width / target_aspect)
            top = (im.height - new_h) // 2
            im = im.crop((0, top, im.width, top + new_h))
        im = im.resize((w_px, h_px), Image.LANCZOS)
        out = Path(output_path)
        out.parent.mkdir(parents=True, exist_ok=True)
        im.save(out, format="PNG", dpi=(dpi, dpi))
    return {
        "output": str(out),
        "width_px": w_px,
        "height_px": h_px,
        "dpi": dpi,
        "width_in": width_in,
        "height_in": height_in,
        "warning": WRAP_WARNING,
        "note": "Upscaling a mockup does not add true print detail. Generate or re-render at print size when possible; use this wrap for layout and test prints.",
    }


def pre_publish_checklist(image_path, ai_text_rendered=False, overlay_text_applied=False, product_confirmed_tumbler=False):
    """Pre-publish checklist. Returns (passed, checks list).

    A design passes ONLY if: file exists and is PNG/JPEG, no AI-rendered text,
    product is manually confirmed as a tumbler (never auto-passed), and if
    text is needed, it was applied via real-font overlay, not the image model.
    """
    from PIL import Image
    checks = []
    src = Path(image_path)
    if not src.exists():
        checks.append(("FAIL", "File exists", "File not found."))
        return False, checks
    checks.append(("PASS", "File exists", str(src)))
    if src.suffix.lower() not in (".png", ".jpg", ".jpeg"):
        checks.append(("FAIL", "Format is PNG/JPEG", f"Got {src.suffix}."))
    else:
        checks.append(("PASS", "Format is PNG/JPEG", src.suffix))
    try:
        with Image.open(src) as im:
            checks.append(("PASS" if im.width >= 1024 and im.height >= 1024 else "FAIL",
                           "Mockup resolution at least 1024px", f"{im.width}x{im.height}"))
            dpi = im.info.get("dpi", (0, 0))[0] if isinstance(im.info.get("dpi"), tuple) else im.info.get("dpi", 0)
            if dpi and dpi >= 299.5:
                checks.append(("PASS", "Print DPI metadata 300+", f"{dpi} DPI"))
            else:
                checks.append(("INFO", "Print DPI metadata 300+", "Not 300 DPI yet — run build_wrap before printing."))
    except Exception as exc:
        checks.append(("FAIL", "Image readable", str(exc)))
    if ai_text_rendered:
        checks.append(("FAIL", "No AI-rendered text", "Image model rendered text — regenerate text-free and overlay with a real font."))
    else:
        checks.append(("PASS", "No AI-rendered text", "Text-free generation confirmed by the requester."))
    if product_confirmed_tumbler:
        checks.append(("PASS", "Product is a tumbler (manual confirm)", "Confirmed by a human looking at the image."))
    else:
        checks.append(("FAIL", "Product is a tumbler (manual confirm)", "Not confirmed — look at the image: it must be a tumbler, not a can, mug, or card."))
    if overlay_text_applied:
        checks.append(("PASS", "Text applied via real font (if text needed)", "Overlay tool used."))
    else:
        checks.append(("INFO", "Text applied via real font (if text needed)", "No overlay applied — fine for text-free designs, required if the design needs a name/brand."))
    passed = all(status != "FAIL" for status, _, _ in checks)
    return passed, checks
